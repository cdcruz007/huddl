  // ── Compatibility scoring algorithm ────────────────────────────────────
  double _calculateCompatibility(MatchableParent parent, List<String> userStages) {
    double score = 0.0;
    final userChildren = _onboarding.children;
    final userGroups = _groupService.getAllDefaultGroups().map((g) => g.id).toList();

    // 1. Same borough = base match (30%)
    final userBorough = _getUserBorough();
    if (parent.borough == userBorough) score += 0.30;

    // 2. Similar child ages (25%)
    if (userChildren.isNotEmpty && parent.childAges.isNotEmpty) {
      for (final childMap in userChildren) {
        final birthday = childMap['birthday'];
        if (birthday != null) {
          final childAge = _parseChildAgeMonths(birthday);
          for (final parentChildAge in parent.childAges) {
            final parentAge = _parseAgeStringToMonths(parentChildAge);
            final ageDiff = (childAge - parentAge).abs();
            if (ageDiff <= 3) {
              score += 0.25;
              break;
            } else if (ageDiff <= 6) {
              score += 0.18;
              break;
            } else if (ageDiff <= 12) {
              score += 0.10;
              break;
            }
          }
        }
      }
    } else if (userStages.isNotEmpty && parent.stagesOfLife.isNotEmpty) {
      // Match on life stage if no children data
      final overlap = userStages.where((s) => parent.stagesOfLife.contains(s)).length;
      score += (overlap / max(1, userStages.length)) * 0.25;
    }

    // 3. Shared groups (25%)
    if (userGroups.isNotEmpty && parent.groupIds.isNotEmpty) {
      final sharedGroups = userGroups.where((g) => parent.groupIds.contains(g)).length;
      score += (sharedGroups / max(1, parent.groupIds.length)) * 0.25;
    }

    // 4. Common meetup attendance (20%)
    final goingMeetups = _meetupService.meetups.where((m) => m.isGoing).toList();
    if (goingMeetups.isNotEmpty) {
      final sharedMeetups = goingMeetups.where(
        (m) => m.attendeeNames.any((name) => parent.name.startsWith(name.split(' ').first)),
      ).length;
      score += (sharedMeetups / max(1, goingMeetups.length)) * 0.20;
    } else {
      // Bonus for similar interests
      score += 0.08;
    }

    return score.clamp(0.0, 1.0);
  }

