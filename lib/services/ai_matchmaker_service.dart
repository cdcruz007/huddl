  /// Call Gemini API to generate personalised meetup suggestions
  Future<Map<String, dynamic>> _getAiSuggestions(
    String userName,
    String borough,
    List<String> userStages,
    List<Map<String, String>> userChildren,
    List<MatchableParent> topMatches,
  ) async {
    final childContext = StringBuffer();
    for (final child in userChildren) {
      final name = child['name'] ?? 'Child';
      final birthday = child['birthday'];
      if (birthday != null) {
        final months = _parseChildAgeMonths(birthday);
        childContext.writeln('- $name: ${months < 12 ? "$months months" : "${months ~/ 12} years"} old');
      }
    }

    final matchContext = topMatches
        .take(4)
        .map((p) =>
            '${p.name} (${p.childAges.join(", ")}, interests: ${p.interests.join(", ")})')
        .join('\n');

    final systemPrompt = '''You are the huddl AI Matchmaker for a UK parents' community app. Generate personalised meetup suggestions based on parent compatibility.

RESPOND IN EXACT JSON FORMAT (no markdown, no backticks, just raw JSON):
{
  "meetups": [
    {
      "title": "Creative meetup title",
      "description": "2-3 sentence engaging description that mentions specific matched parents and why they'd get along",
      "reasoning": "1 sentence explaining the AI matching logic"
    }
  ]
}

Generate exactly 5 meetup suggestions. Use British English. Be warm, specific and mention real parent names from the matches.''';

    final requestBody = {
      'system_instruction': {
        'parts': [
          {'text': systemPrompt}
        ]
      },
      'contents': [
        {
          'role': 'user',
          'parts': [
            {
              'text': '''Generate meetup suggestions for $userName in $borough.

User's stages: ${userStages.join(', ')}
User's children:
${childContext.isNotEmpty ? childContext.toString() : 'No children info'}
Parent type: ${_onboarding.parentType ?? 'parent'}

Top compatible parents nearby:
$matchContext

Please suggest 5 diverse meetups: 1) playdate, 2) coffee morning, 3) outdoor activity, 4) social evening, 5) themed meetup.'''
            }
          ]
        }
      ],
      'generationConfig': {
        'temperature': 0.85,
        'topP': 0.95,
        'maxOutputTokens': 1024,
      },
    };

    final url = Uri.parse(
        '$_geminiBaseUrl/$_geminiModel:generateContent?key=$_geminiApiKey');

    final response = await http
        .post(
          url,
          headers: {'Content-Type': 'application/json'},
          body: jsonEncode(requestBody),
        )
        .timeout(const Duration(seconds: 15));

    if (response.statusCode == 200) {
      final data = jsonDecode(response.body);
      final candidates = data['candidates'] as List?;
      if (candidates != null && candidates.isNotEmpty) {
        final content = candidates[0]['content'];
        final parts = content['parts'] as List?;
        if (parts != null && parts.isNotEmpty) {
          var text = (parts[0]['text'] as String? ?? '').trim();
          text = text.replaceAll(RegExp(r'^```json\s*'), '');
          text = text.replaceAll(RegExp(r'\s*```$'), '');
          text = text.trim();
          return jsonDecode(text) as Map<String, dynamic>;
        }
      }
    }

    throw Exception('No valid AI response');
  }

