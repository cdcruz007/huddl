      organiserId: 'current_user',
      attendeeCount: 1,
      isGoing: true,
      attendeeNames: [_onboarding.name ?? 'You'],
      isFree: true,
      borough: _getUserBorough(),
      privacy: MeetupPrivacy.public,
      invitees: suggestion.matchedParents
          .map((p) => MeetupAttendee(
                id: p.id,
                name: p.name,
                avatarUrl: p.avatarUrl,
                status: 'invited',
              ))
          .toList(),
    );

    _meetupService.createMeetup(meetup);
    return meetup;
  }

  // ── Helpers ────────────────────────────────────────────────────────────
  String _getUserBorough() {
    final pc = _onboarding.postcode;
    if (pc != null) {
      return _postcode.getBoroughFromPostcode(pc) ?? 'Cambridge';
    }
    return 'Cambridge';
  }

  int _parseChildAgeMonths(String birthday) {
    try {
      final parts = birthday.split('/');
      if (parts.length >= 2) {
        final month = int.parse(parts[0]);
        final year = int.parse(parts.last);
        final now = DateTime.now();
        final birth = DateTime(year, month);
        return ((now.difference(birth).inDays) / 30.44).round();
      }
    } catch (_) {}
    return 24;
  }

  int _parseAgeStringToMonths(String ageStr) {
    final lower = ageStr.toLowerCase();
    final numMatch = RegExp(r'(\d+)').firstMatch(lower);
    if (numMatch == null) return 24;
    final num = int.parse(numMatch.group(1)!);
    if (lower.contains('year')) return num * 12;
    return num;
  }

  DateTime _nextWeekday(DateTime from, int weekday, {int weeksAhead = 0}) {
    var d = from.add(Duration(days: 1 + weeksAhead * 7));
    while (d.weekday != weekday) {
      d = d.add(const Duration(days: 1));
    }
    return d;
  }

  String _formatDate(DateTime d) {
    const dayAbbr = ['MON', 'TUE', 'WED', 'THU', 'FRI', 'SAT', 'SUN'];
    const monthAbbr = [
      'JAN', 'FEB', 'MAR', 'APR', 'MAY', 'JUN',
      'JUL', 'AUG', 'SEP', 'OCT', 'NOV', 'DEC'
    ];
    return '${dayAbbr[d.weekday - 1]}, ${monthAbbr[d.month - 1]} ${d.day}';
  }
