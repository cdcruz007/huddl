/// A parent profile used for matching
class MatchableParent {
  final String id;
  final String name;
  final String? avatarUrl;
  final String? borough;
  final List<String> stagesOfLife;
  final List<String> childAges; // e.g. "14 months", "3 years"
  final List<String> groupIds;
  final List<String> interests;
  final double compatibilityScore;

  const MatchableParent({
    required this.id,
    required this.name,
    this.avatarUrl,
    this.borough,
    this.stagesOfLife = const [],
    this.childAges = const [],
    this.groupIds = const [],
    this.interests = const [],
    this.compatibilityScore = 0.0,
  });

  MatchableParent copyWith({double? compatibilityScore}) => MatchableParent(
    id: id,
    name: name,
    avatarUrl: avatarUrl,
    borough: borough,
    stagesOfLife: stagesOfLife,
    childAges: childAges,
    groupIds: groupIds,
    interests: interests,
    compatibilityScore: compatibilityScore ?? this.compatibilityScore,
  );
}

/// A suggested meetup generated by the AI matchmaker
class SuggestedMeetup {
  final String id;
  final String title;
  final String description;
  final String category;
  final String suggestedLocation;
  final String suggestedDate;
  final String suggestedTime;
  final DateTime suggestedDateTime;
  final List<MatchableParent> matchedParents;
  final double confidenceScore; // 0.0 to 1.0
  final String reasoning;
  final String? weatherNote;
  final String iconEmoji;

  const SuggestedMeetup({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.suggestedLocation,
    required this.suggestedDate,
    required this.suggestedTime,
    required this.suggestedDateTime,
    required this.matchedParents,
    required this.confidenceScore,
    required this.reasoning,
    this.weatherNote,
    required this.iconEmoji,
  });
}

