/// A parent profile used for matching
class MatchableParent {
  final String id;
  final String name;
  final String? avatarUrl;
  final String? borough;
  final List<String> stagesOfLife;
  final List<String> childAges;
  final List<String> groupIds;
  final List<String> interests;
  final double compatibilityScore;

  const MatchableParent({
    required this.id,
    required this.name,
    this.avatarUrl,
    this.borough,
    this.stagesOfLife = const [],
    this.childAges = const [],
    this.groupIds = const [],
    this.interests = const [],
    this.compatibilityScore = 0.0,
  });

  MatchableParent copyWith({double? compatibilityScore}) => MatchableParent(
        id: id,
        name: name,
        avatarUrl: avatarUrl,
        borough: borough,
        stagesOfLife: stagesOfLife,
        childAges: childAges,
        groupIds: groupIds,
        interests: interests,
        compatibilityScore: compatibilityScore ?? this.compatibilityScore,
      );
}

/// A suggested meetup generated by the AI matchmaker
