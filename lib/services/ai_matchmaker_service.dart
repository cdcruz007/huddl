  /// Call Gemini API to generate personalised meetup suggestions
  Future<Map<String, dynamic>> _getAiSuggestions(
    String userName,
    String borough,
    List<String> userStages,
    List<Map<String, String>> userChildren,
    List<MatchableParent> topMatches,
  ) async {
    final childContext = StringBuffer();
    for (final child in userChildren) {
      final name = child['name'] ?? 'Child';
      final birthday = child['birthday'];
      if (birthday != null) {
        final months = _parseChildAgeMonths(birthday);
        childContext.writeln('- $name: ${months < 12 ? "$months months" : "${months ~/ 12} years"} old');
      }
    }

    final matchContext = topMatches
        .take(4)
        .map((p) =>
            '${p.name} (${p.childAges.join(", ")}, interests: ${p.interests.join(", ")})')
        .join('\n');

    final basePrompt = GeminiSystemPromptBuilder().buildMatchmakerPrompt(
      matchProfileSummary:
          'Top compatible parents nearby:\n$matchContext',
      matchBorough: borough,
    );
    final systemPrompt = '$basePrompt\n'
        'RESPOND IN EXACT JSON FORMAT (no markdown, no backticks, just raw JSON):\n'
        '{\n'
        '  "meetups": [\n'
        '    {\n'
        '      "title": "Creative meetup title",\n'
        '      "description": "2-3 sentence engaging description that mentions specific '
        'matched parents and why they\'d get along",\n'
        '      "reasoning": "1 sentence explaining the AI matching logic"\n'
        '    }\n'
        '  ]\n'
        '}\n\n'
        'Generate exactly 5 meetup suggestions. Be warm, specific and mention real parent '
        'names from the matches.\n'
        'All meetup locations MUST be within $borough.';

    final requestBody = {
      'system_instruction': {
        'parts': [
          {'text': systemPrompt}
        ]
      },
      'contents': [
        {
          'role': 'user',
          'parts': [
            {
              'text': '''Generate meetup suggestions for $userName in $borough.

User's stages: ${userStages.join(', ')}
User's children:
