// =============================================================================
// MESSAGES AI SERVICE
//
// Powers the "Invisible AI" strategy for the Messages Tab:
//   - Predictive NLP search with auto-suggestions
//   - Adaptive interface reordering based on usage patterns
//   - Personalized quick-action recommendations
//   - AI-driven conversation prioritisation
//   - Feedback loops (like/dislike for learning)
//   - Voice command intent parsing
//   - Conversation health scoring
